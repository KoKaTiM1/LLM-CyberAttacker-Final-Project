# Graph builder
# ---------------------------------------------------------------------------

def build_cyber_attack_graph():
    """
    Build and compile the LangGraph graph for the cyber-attack workflow.

    Returns:
        A compiled graph object with .invoke() / .stream() / .get_graph() etc.
    """
    workflow = StateGraph(CyberState)

    # Register nodes
    workflow.add_node("check_connections", check_connections_node)
    workflow.add_node("validate_file", validate_file_node)
    workflow.add_node("analyze_vulnerability", analyze_vulnerability_node)
    workflow.add_node("create_attack_script", create_attack_script_node)
    workflow.add_node("execute_in_sandbox", execute_in_sandbox_node)
    workflow.add_node("handle_error", handle_error_node)
    workflow.add_node("workflow_complete", workflow_complete_node)

    # Start and end
    workflow.add_edge(START, "check_connections")
    workflow.add_edge("workflow_complete", END)
    workflow.add_edge("handle_error", END)

    # Conditional edges
    workflow.add_conditional_edges(
        "check_connections",
        route_after_check_connections,
        ["validate_file", "handle_error"],
    )
    workflow.add_conditional_edges(
        "validate_file",
        route_after_validate_file,
        ["analyze_vulnerability", "handle_error"],
    )
    workflow.add_conditional_edges(
        "analyze_vulnerability",
        route_after_analyze,
        ["create_attack_script", "handle_error"],
    )
    workflow.add_conditional_edges(
        "create_attack_script",
        route_after_create_script,
        ["execute_in_sandbox", "handle_error"],
    )
    workflow.add_conditional_edges(
        "execute_in_sandbox",
        route_after_sandbox,
        ["workflow_complete", "handle_error"],
    )

    # Compile to a runnable graph
    app = workflow.compile()
    return app


# Compiled graph exposed at module level
cyber_attack_app = build_cyber_attack_graph()


# ---------------------------------------------------------------------------
# Convenience helpers
# ---------------------------------------------------------------------------

def run_cyber_attack(file_path: str) -> CyberState:
    """
    Convenience wrapper to run the whole graph on a given file path.

    Example:
        from src.modules.cyber_attack_graph import run_cyber_attack
        result_state = run_cyber_attack("path/to/test.c")
    """
    initial_state: CyberState = {
        "file_path": str(file_path),
        "logs": [],
    }
    result: CyberState = cyber_attack_app.invoke(initial_state)
    return result


def run_cyber_attack_on_folder(
    folder_path: str,
    allowed_suffixes: Optional[List[str]] = None,
) -> Dict[str, CyberState]:
    """
    Run the cyber-attack LangGraph workflow on all files in a given folder.

    This is a convenience helper for batch processing. It is intentionally kept
    outside the graph itself so the graph logic remains "single-file" and
    reusable in Studio, tests, etc.

    Args:
        folder_path:
            Path to the folder containing input files.

        allowed_suffixes:
            Optional list of file suffixes (extensions) to include.
            If None, defaults to [".c", ".txt"].

    Returns:
        A dictionary mapping each file name to the final CyberState produced by
        the graph for that file.

        Example:
            {
                "File1.c": <CyberState for File1.c>,
                "File2.txt": <CyberState for File2.txt>,
            }
    """
    folder = Path(folder_path)

    # Validate that the provided path is a folder
    if not folder.exists() or not folder.is_dir():
        raise ValueError(f"Folder does not exist or is not a directory: {folder}")

    # Default extensions: same as your getFile() logic (.c and .txt)
    if allowed_suffixes is None:
        allowed_suffixes = [".c", ".txt"]

    results: Dict[str, CyberState] = {}

    # Iterate over all matching files in the folder
    for entry in sorted(folder.iterdir()):
        # Skip non-files (directories, symlinks, etc.)
        if not entry.is_file():
            continue

        # Filter by allowed suffix list
        if entry.suffix.lower() not in (s.lower() for s in allowed_suffixes):
            continue

        # Run the existing single-file helper on this file
        state = run_cyber_attack(str(entry))
        results[entry.name] = state

    return results


def show_graph_png() -> bytes:
    """
    Render the workflow as a PNG (Mermaid) and return raw bytes.

    Typical usage in a notebook:

        from IPython.display import Image, display
        from src.modules.cyber_attack_graph import show_graph_png

        display(Image(show_graph_png()))

    This uses LangGraph's get_graph(xray=True).draw_mermaid_png().
    """
    graph = cyber_attack_app.get_graph(xray=True)
    png = graph.draw_mermaid_png()
    return png


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def main() -> None:
    """
    CLI helper:
    - Saves the LangGraph diagram as 'cyber_attack_graph.png' in the current dir.
    - Optionally runs the full flow on a single file (--file).
    - Optionally runs the flow on all files in a folder (--folder).

    Examples:
        python -m src.modules.cyber_attack_graph
        python -m src.modules.cyber_attack_graph --out diagrams/attack_flow.png
        python -m src.modules.cyber_attack_graph --file src/data/LCP-Data set/Files/File2.txt
        python -m src.modules.cyber_attack_graph --folder "src/data/LCP-Data set/Files"
    """
    import argparse

    parser = argparse.ArgumentParser(description="Cyber-attack LangGraph visualizer")
    parser.add_argument(
        "--out",
        default="cyber_attack_graph.png",
        help="Output PNG path for the graph diagram",
    )
    parser.add_argument(
        "--file",
        help="Optional C/TXT file to run the cyber-attack flow on",
    )
    parser.add_argument(
        "--folder",
        help="Optional folder containing multiple files to process",
    )
    args = parser.parse_args()

    # 1) Export graph PNG
    png_bytes = show_graph_png()
    out_path = Path(args.out)
    out_path.write_bytes(png_bytes)
    print(f"Saved graph diagram to: {out_path}")

    # 2) Run on a single file, if requested
    if args.file:
        print(f"\n=== Running workflow on single file: {args.file} ===")
        result_state = run_cyber_attack(args.file)

        print("\n--- Workflow logs ---")
        for line in result_state.get("logs", []):
            print(line)

        print("\nFinal error_message:", result_state.get("error_message"))
        print("Sandbox result (truncated):")
        sr = result_state.get("sandbox_result", "")
        print(sr[:500] + ("..." if len(sr) > 500 else ""))

    # 3) Run on all files in a folder, if requested
    if args.folder:
        print(f"\n=== Running workflow on all files in folder: {args.folder} ===")
        batch_results = run_cyber_attack_on_folder(args.folder)

        # Print a concise summary per file
        for filename, state in batch_results.items():
            error_message = state.get("error_message")
            success = not bool(error_message)
            print(f"\n[{filename}]")
            print(f"  Connections OK: {state.get('connections_ok', False)}")
            print(f"  Success:       {success}")
            print(f"  Error message: {error_message or 'None'}")

        print("\nBatch processing completed.")


if __name__ == "__main__":
    main()
