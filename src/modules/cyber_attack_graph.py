"""
Cyber-attack LangGraph workflow (visual, Graph API based).

This module defines a LangGraph StateGraph that wraps your existing
LLM.py, Agent.py, and sandbox.py logic into a visual workflow that you
can render as a graph (Mermaid / PNG) and run end-to-end.

It does NOT modify your existing modules. It only imports and orchestrates them.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional

# TypedDict must come from typing_extensions on Python < 3.12
try:
    from typing_extensions import TypedDict
except ImportError:
    # Fallback if typing_extensions is not installed or on newer Python
    from typing import TypedDict  # type: ignore

from langgraph.graph import StateGraph, START, END  # pip install langgraph

# Existing project modules (keep package-relative imports)
from .LLM import getFile, sendToLLM, checkConnectionWithOllama
from .Agent import resultsFromLLM
from .sandbox import SandboxManager


# ---------------------------------------------------------------------------
# Logging configuration
# ---------------------------------------------------------------------------

logger = logging.getLogger(__name__)
if not logger.handlers:
    # Basic configuration if not already set by the application
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(name)s - %(levelname)s - %(message)s",
    )


# ---------------------------------------------------------------------------
# Shared state definition (TypedDict used by LangGraph)
# ---------------------------------------------------------------------------

class CyberState(TypedDict, total=False):
    """
    Shared state for the LangGraph workflow.

    Fields:
        file_path:
            Input C file path as string (absolute or relative).

        file_content:
            Source code contents as a single string.

        vulnerability_data:
            Parsed vulnerability info (JSON-like dict) returned by the LLM.

        llm_response:
            Raw LLM response text (stringified JSON or fallback text).

        attack_script:
            Exploit script generated by Agent.py.

        sandbox_result:
            JSON string of sandbox execution results.

        connections_ok:
            True if the LLM connection check passed.

        error_message:
            Last error encountered in the workflow, if any.

        logs:
            List of human-readable log lines describing what happened.
    """

    file_path: str
    file_content: str
    vulnerability_data: Dict[str, Any]
    llm_response: str
    attack_script: str
    sandbox_result: str
    connections_ok: bool
    error_message: str
    logs: List[str]


def _append_log(state: CyberState, message: str) -> None:
    """
    Append a log line to state['logs'] and log via standard logging.

    This helper keeps logging and state updates consistent across all nodes.
    """
    logs = state.get("logs") or []
    logs.append(message)
    state["logs"] = logs
    logger.info(message)


# ---------------------------------------------------------------------------
# Node implementations
# ---------------------------------------------------------------------------

def check_connections_node(state: CyberState) -> CyberState:
    """
    Node 1 – check LLM (and later agent / sandbox) connectivity.

    Responsibilities:
    - Call existing checkConnectionWithOllama().
    - Set 'connections_ok' and 'error_message' accordingly.
    """
    _append_log(state, "Step 1: Checking API connections...")

    try:
        ok_llm = checkConnectionWithOllama()
        # TODO: add checkAPIconnectionWithAgent() and sandbox connectivity if needed

        if ok_llm:
            state["connections_ok"] = True
            _append_log(state, "All API connections successful")
        else:
            msg = "LLM API connection lost"
            state["connections_ok"] = False
            state["error_message"] = msg
            _append_log(state, msg)

    except Exception as exc:
        msg = f"Connection check failed: {exc}"
        state["connections_ok"] = False
        state["error_message"] = msg
        _append_log(state, msg)

    return state


def validate_file_node(state: CyberState) -> CyberState:
    """
    Node 2 – validate the input C file and load its contents.

    Responsibilities:
    - Use getFile(path) from LLM.py.
    - On success, read file contents into 'file_content'.
    - On failure, set 'error_message'.
    """
    _append_log(state, "Step 2: Validating file...")

    path = Path(state["file_path"])

    try:
        ok = getFile(path)

        if ok:
            state["file_content"] = path.read_text(encoding="utf-8", errors="ignore")
            _append_log(state, "File validation successful")
        else:
            msg = "File validation failed (see getFile for details)"
            state["error_message"] = msg
            _append_log(state, msg)

    except Exception as exc:
        msg = f"File validation error: {exc}"
        state["error_message"] = msg
        _append_log(state, msg)

    return state


def analyze_vulnerability_node(state: CyberState) -> CyberState:
    """
    Node 3 – send file to LLM and parse vulnerability description.

    Responsibilities:
    - Call sendToLLM(file_content) from LLM.py.
    - Extract the 'response' field.
    - Attempt to parse JSON into 'vulnerability_data'.
    - Fallback to a default structure if JSON parsing fails.
    """
    _append_log(state, "Step 3: Analyzing vulnerabilities with LLM...")

    file_content = state.get("file_content", "")
    if not file_content:
        msg = "No file content to analyze"
        state["error_message"] = msg
        _append_log(state, msg)
        return state

    try:
        llm_response = sendToLLM(file_content)
        if not llm_response:
            msg = "No response from LLM"
            state["error_message"] = msg
            _append_log(state, msg)
            return state

        _append_log(state, f"Received response from LLM: {llm_response}")

        # Extract the 'response' field per your existing logic
        response_text = llm_response.get("response", "")

        if not response_text:
            msg = "LLM response did not contain a 'response' field"
            state["error_message"] = msg
            _append_log(state, msg)
            return state

        state["llm_response"] = response_text

        # Try to parse as JSON; otherwise use fallback structure
        try:
            vuln_data = json.loads(response_text)
        except json.JSONDecodeError:
            vuln_data = {
                "vulnerabilities": [
                    {
                        "Type": "buffer overflow",
                        "Location": "line 6",
                        "Explanation": "strcpy without bounds checking found in the code",
                    }
                ]
            }

        state["vulnerability_data"] = vuln_data
        _append_log(state, f"Parsed vulnerability data: {vuln_data}")
        _append_log(state, "Vulnerability analysis completed")

    except Exception as exc:
        msg = f"Vulnerability analysis failed: {exc}"
        state["error_message"] = msg
        _append_log(state, msg)

    return state


def create_attack_script_node(state: CyberState) -> CyberState:
    """
    Node 4 – generate exploit script via Agent.py.

    Responsibilities:
    - Call resultsFromLLM(llm_response) from Agent.py.
    - Store script in 'attack_script'.
    """
    _append_log(state, "Step 4: Creating attack script with Agent...")

    llm_response = state.get("llm_response", "")
    if not llm_response:
        msg = "Cannot create attack script – missing LLM response"
        state["error_message"] = msg
        _append_log(state, msg)
        return state

    try:
        script = resultsFromLLM(llm_response)
        state["attack_script"] = script
        _append_log(state, f"Generated attack script ({len(script)} chars)")
    except Exception as exc:
        msg = f"Script creation failed: {exc}"
        state["error_message"] = msg
        _append_log(state, msg)

    return state


def execute_in_sandbox_node(state: CyberState) -> CyberState:
    """
    Node 5 – execute the exploit in configured sandboxes.

    Responsibilities:
    - Load sandbox_config.json via SandboxManager.
    - Connect to environments and run a health-check script.
    - Execute the real exploit script with vulnerability data.
    - Store results in 'sandbox_result'.
    """
    _append_log(state, "Step 5: Executing attack script in sandbox...")

    attack_script = state.get("attack_script", "")
    if not attack_script:
        msg = "No attack script available for sandbox execution"
        state["error_message"] = msg
        _append_log(state, msg)
        return state

    # Adjust relative path if your config lives elsewhere
    config_path = Path(__file__).parent.parent / "config" / "sandbox_config.json"

    if not config_path.exists():
        msg = f"Sandbox config file not found: {config_path}"
        state["error_message"] = msg
        _append_log(state, msg)
        return state

    sandbox_manager = SandboxManager(config_file=str(config_path))

    if not sandbox_manager.environments:
        msg = "No sandbox environments enabled in config"
        state["error_message"] = msg
        _append_log(state, msg)
        return state

    enabled_envs = list(sandbox_manager.environments.keys())
    _append_log(
        state,
        f"Loaded {len(enabled_envs)} environment(s): {', '.join(enabled_envs)}",
    )

    try:
        _append_log(state, "Connecting to sandbox environments...")
        if not sandbox_manager.connect_all():
            msg = "Failed to connect to any sandbox environment"
            state["error_message"] = msg
            _append_log(state, msg)
            return state

        _append_log(state, "Connected to sandbox environments")

        # Optional: run a quick health check script
        _append_log(state, "Running basic test script on all environments...")
        test_script = "print('Sandbox test successful')"
        test_results = sandbox_manager.run_test_on_all(test_script)

        ok_envs = [name for name, r in test_results.items() if r.success]
        bad_envs = [name for name, r in test_results.items() if not r.success]

        if not ok_envs:
            msg = f"All test runs failed. Failed envs: {', '.join(bad_envs)}"
            state["error_message"] = msg
            _append_log(state, msg)
            return state

        _append_log(
            state,
            f"Test passed in {len(ok_envs)} environment(s); "
            f"failures: {', '.join(bad_envs) if bad_envs else 'none'}",
        )

        # Real exploit execution
        _append_log(state, "Executing attack script in all environments...")
        results = sandbox_manager.execute_exploit(
            exploit_script=attack_script,
            vulnerability_data=state.get("vulnerability_data", {}),
        )

        state["sandbox_result"] = json.dumps(results, indent=2)

        successful_envs: List[str] = []
        failed_envs: List[str] = []
        for env_name, result in results.items():
            analysis = result.get("exploitation_analysis", {})
            if analysis.get("exploitation_successful", False):
                successful_envs.append(env_name)
                _append_log(state, f"{env_name}: attack successful")
            else:
                failed_envs.append(env_name)
                _append_log(state, f"{env_name}: attack failed")

        if successful_envs:
            _append_log(
                state,
                f"Attack succeeded in {len(successful_envs)} environment(s): "
                f"{', '.join(successful_envs)}",
            )
        else:
            _append_log(
                state,
                f"Attack failed in all {len(failed_envs)} environment(s)",
            )

    except Exception as exc:
        msg = f"Sandbox execution error: {exc}"
        state["error_message"] = msg
        _append_log(state, msg)
    finally:
        try:
            sandbox_manager.disconnect_all()
            _append_log(state, "Sandbox cleanup completed")
        except Exception as exc:
            _append_log(state, f"Sandbox cleanup error: {exc}")

    return state


def handle_error_node(state: CyberState) -> CyberState:
    """
    Node used as a sink for errors from any previous step.

    Responsibilities:
    - Log the final error for visibility.
    """
    msg = state.get("error_message") or "Unknown error (handle_error_node)"
    _append_log(state, f"Handling error: {msg}")
    return state


def workflow_complete_node(state: CyberState) -> CyberState:
    """
    Final node – marks logical completion of the workflow.

    Responsibilities:
    - Add a final log entry indicating completion.
    """
    _append_log(state, "Workflow completed")
    return state


# ---------------------------------------------------------------------------
# Routing / conditional edges
# ---------------------------------------------------------------------------

def _has_error(state: CyberState) -> bool:
    """
    Return True if the state currently carries an error message.
    """
    return bool(state.get("error_message"))


def route_after_check_connections(state: CyberState) -> str:
    """
    Router after check_connections_node.
    """
    return "handle_error" if _has_error(state) else "validate_file"


def route_after_validate_file(state: CyberState) -> str:
    """
    Router after validate_file_node.
    """
    return "handle_error" if _has_error(state) else "analyze_vulnerability"


def route_after_analyze(state: CyberState) -> str:
    """
    Router after analyze_vulnerability_node.
    """
    return "handle_error" if _has_error(state) else "create_attack_script"


def route_after_create_script(state: CyberState) -> str:
    """
    Router after create_attack_script_node.
    """
    return "handle_error" if _has_error(state) else "execute_in_sandbox"


def route_after_sandbox(state: CyberState) -> str:
    """
    Router after execute_in_sandbox_node.
    """
    return "handle_error" if _has_error(state) else "workflow_complete"


